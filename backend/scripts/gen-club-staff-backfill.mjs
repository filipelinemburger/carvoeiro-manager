#!/usr/bin/env node
// Generates the club-staff backfill migration from the seed research data
// (backend/src/main/resources/seed/club-staff.json).
//
// Careers created before clubs had a comissão técnica have no staff rows at all; this script
// emits deterministic INSERT statements that carry the researched staff onto them. New careers
// already get the same rows at creation time via SaveGameService.seedClubStaff. Run it whenever
// the seed staff data changes:
//
//   node backend/scripts/gen-club-staff-backfill.mjs [migrationVersion]
//
// (default migrationVersion is 50 — bump it if a concurrent change has already claimed V50,
// and re-run.)
//
// Derivation must stay identical to SaveGameService.seedClubStaff:
//   - quality = StaffQuality.forAverage((primaryAttribute + secondaryAttribute) / 2)
//   - wage    = that tier's StaffQuality.monthlyWage()
//   - the club is resolved by shortName (SaveGameService keys clubIdByShortName the same way)
//
// Three guards keep the migration safe on a live save (design spec §9):
//   (a) never fill a slot that already has someone — respects UNIQUE (club_id, role) and, more
//       importantly, never overwrites a hire the player paid for;
//   (b) never insert a person who already exists somewhere in that save — a pool professional the
//       player hired must not also appear in a rival's dugout;
//   (c) TECNICO only: skip the save's managed club, because there the head coach is the player.
//       Expressed as a SQL predicate, not resolved here: managed_club_id is per-save runtime state,
//       unknown at generation time.
// (a) and (b) also make the migration idempotent — replaying it inserts nothing new.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const SEED_DIR = path.join(SCRIPT_DIR, "..", "src", "main", "resources", "seed");
const MIGRATION_DIR = path.join(SCRIPT_DIR, "..", "src", "main", "resources", "db", "migration");

const migrationVersion = process.argv[2] ? Number(process.argv[2]) : 50;
if (!Number.isInteger(migrationVersion) || migrationVersion <= 0) {
    throw new Error(`Invalid migration version: ${process.argv[2]}`);
}

function sqlString(value) {
    return `'${value.replace(/'/g, "''")}'`;
}

// Must stay identical to StaffQuality.forAverage / StaffQuality.monthlyWage.
function tierFor(primaryAttribute, secondaryAttribute) {
    const average = (primaryAttribute + secondaryAttribute) / 2;
    if (average >= 15) return { quality: "EXCELENTE", wage: "80000.00" };
    if (average >= 12) return { quality: "BOM", wage: "45000.00" };
    return { quality: "REGULAR", wage: "20000.00" };
}

function staffStatement(clubShortName, member) {
    const { quality, wage } = tierFor(member.primaryAttribute, member.secondaryAttribute);
    // Guard (c): only the head-coach slot of the save's own managed club is the player's.
    const managedClubGuard = member.role === "TECNICO"
        ? "\n  AND c.id IS DISTINCT FROM g.managed_club_id"
        : "";
    return `INSERT INTO staff (id, save_game_id, club_id, role, quality, name, wage,
                   primary_attribute, secondary_attribute)
SELECT gen_random_uuid(), c.save_game_id, c.id, ${sqlString(member.role)}, ${sqlString(quality)}, ${sqlString(member.name)}, ${wage}, ${member.primaryAttribute}, ${member.secondaryAttribute}
FROM clubs c
JOIN save_games g ON g.id = c.save_game_id
WHERE c.short_name = ${sqlString(clubShortName)}
  AND NOT EXISTS (SELECT 1 FROM staff s
                   WHERE s.club_id = c.id AND s.role = ${sqlString(member.role)})
  AND NOT EXISTS (SELECT 1 FROM staff s
                   WHERE s.save_game_id = c.save_game_id AND s.name = ${sqlString(member.name)})${managedClubGuard};`;
}

function main() {
    const clubStaff = JSON.parse(readFileSync(path.join(SEED_DIR, "club-staff.json"), "utf8"));

    const statements = [];
    for (const entry of clubStaff) {
        for (const member of entry.staff) {
            statements.push(staffStatement(entry.clubShortName, member));
        }
    }

    const header = `-- GENERATED by backend/scripts/gen-club-staff-backfill.mjs from seed/club-staff.json — do not hand-edit.
--
-- Backfills each club's researched coaching staff (spec §9) onto EXISTING careers. New careers
-- already get these rows at creation time via SaveGameService.seedClubStaff; without this
-- migration an in-progress career never sees a single real comissão técnica and every rival club
-- page stays empty forever.
--
-- Each statement resolves its club by short_name within the save game that owns it, so the rows
-- land on every existing career at once. Three guards keep it safe on a live save:
--   (a) never overwrite an occupied slot — the player's own hires win, and UNIQUE (club_id, role)
--       is never violated;
--   (b) never duplicate someone already employed in that save — a pool professional the player
--       hired must not also turn up in a rival's dugout;
--   (c) never give a save's managed club a head coach — that job is the player's.
-- (a) and (b) also make this migration idempotent: replaying it inserts nothing new.
--
-- A save whose managed club already hired a physio keeps that person while a fresh career gets the
-- researched one: existing saves are not byte-identical to new ones, the same trade V43 accepted.
--
-- ${statements.length} statement(s).
`;

    const sql = [header, ...statements, ""].join("\n");

    const outputPath = path.join(MIGRATION_DIR, `V${migrationVersion}__club_staff.sql`);
    writeFileSync(outputPath, sql, "utf8");

    console.log(`Wrote ${outputPath}`);
    console.log(`  staff statements: ${statements.length}`);
}

main();
