#!/usr/bin/env node
// Generates the V43 research-backfill migration from the seed research data
// (backend/src/main/resources/seed/clubs.json and seed/free-agents.json).
//
// Existing saved careers had their positions/roles derived at random when the
// career was created; this script emits deterministic UPDATE statements that
// carry the researched (name-matched) positions/roles onto existing rows.
// Run it whenever the seed research data changes:
//
//   node backend/scripts/gen-research-backfill.mjs [migrationVersion]
//
// (default migrationVersion is 43 — bump it if a concurrent change has
// already claimed V43, and re-run.)
//
// Serialization must stay byte-identical to SaveGameService.applyResearchedPositionsAndRoles
// / Player.setPositions / Player.setFamiliarRoles:
//   - detailed_position = positions[0]
//   - alt_positions     = positions[1..] joined with ',' (NULL, not '', when there are none)
//   - familiar_roles    = roles joined with ',' (tokens kept verbatim, including +/++ suffix)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const SEED_DIR = path.join(SCRIPT_DIR, "..", "src", "main", "resources", "seed");
const MIGRATION_DIR = path.join(SCRIPT_DIR, "..", "src", "main", "resources", "db", "migration");

const migrationVersion = process.argv[2] ? Number(process.argv[2]) : 43;
if (!Number.isInteger(migrationVersion) || migrationVersion <= 0) {
    throw new Error(`Invalid migration version: ${process.argv[2]}`);
}

function sqlString(value) {
    return `'${value.replace(/'/g, "''")}'`;
}

function altPositionsSql(positions) {
    return positions.length > 1 ? sqlString(positions.slice(1).join(",")) : "NULL";
}

function familiarRolesSql(roles) {
    return sqlString(roles.join(","));
}

function clubPlayerStatement(clubName, player) {
    const [primary, ...rest] = player.positions;
    return `UPDATE players p SET detailed_position = ${sqlString(primary)},
    alt_positions = ${altPositionsSql([primary, ...rest])}, familiar_roles = ${familiarRolesSql(player.roles)}
FROM clubs c
WHERE p.club_id = c.id AND c.name = ${sqlString(clubName)} AND p.name = ${sqlString(player.name)};`;
}

function freeAgentStatement(player) {
    const [primary, ...rest] = player.positions;
    return `UPDATE players SET detailed_position = ${sqlString(primary)},
    alt_positions = ${altPositionsSql([primary, ...rest])}, familiar_roles = ${familiarRolesSql(player.roles)}
WHERE club_id IS NULL AND name = ${sqlString(player.name)};`;
}

function main() {
    const clubs = JSON.parse(readFileSync(path.join(SEED_DIR, "clubs.json"), "utf8"));
    const freeAgents = JSON.parse(readFileSync(path.join(SEED_DIR, "free-agents.json"), "utf8"));

    const clubStatements = [];
    for (const club of clubs.clubPool) {
        for (const player of club.players) {
            if (!player.positions?.length || !player.roles?.length) continue;
            clubStatements.push(clubPlayerStatement(club.name, player));
        }
    }

    const nameCounts = new Map();
    for (const player of freeAgents) {
        nameCounts.set(player.name, (nameCounts.get(player.name) ?? 0) + 1);
    }
    const ambiguousNames = [...nameCounts.entries()].filter(([, count]) => count > 1).map(([name]) => name);

    const freeAgentStatements = [];
    for (const player of freeAgents) {
        if (!player.positions?.length || !player.roles?.length) continue;
        if (nameCounts.get(player.name) > 1) continue; // ambiguous — skip rather than guess
        freeAgentStatements.push(freeAgentStatement(player));
    }

    const header = `-- GENERATED by backend/scripts/gen-research-backfill.mjs from the seed research data — do not hand-edit. Unmatched players (newgens, transfers, renames) keep their V41/V42-derived values (spec §3.1c).
--
-- Backfills researched positions/roles (spec §3.1) onto EXISTING saved careers. New careers
-- already get this data at creation time via SaveGameService.applyResearchedPositionsAndRoles;
-- this migration name-matches (club players: club name + player name; free agents: player name,
-- only where that name is unambiguous across free-agents.json) to carry the same data onto rows
-- that were derived at random before this feature existed. A player with no match keeps their
-- existing detailed_position/alt_positions/familiar_roles untouched.
--
-- KNOWN LIMITATION of matching on the CURRENT club: 27 player names occur at more than one club in
-- the seed pool. If such a player was already transferred in-game to the other club that also has a
-- player of that name, this migration writes the destination club's namesake's data onto them. That
-- costs one player a wrong position profile in an already-diverging save; narrowing the match
-- further would instead cost every untransferred namesake their correct data, which is the worse
-- trade (spec §3.2 already accepts that existing saves are not byte-identical to new ones).
--
-- ${clubStatements.length} club-player statement(s), ${freeAgentStatements.length} free-agent statement(s)
-- (${ambiguousNames.length} free-agent name(s) skipped as ambiguous: ${ambiguousNames.join(", ") || "none"}).
`;

    const sql = [header, ...clubStatements, "", ...freeAgentStatements, ""].join("\n");

    const outputPath = path.join(MIGRATION_DIR, `V${migrationVersion}__research_backfill.sql`);
    writeFileSync(outputPath, sql, "utf8");

    console.log(`Wrote ${outputPath}`);
    console.log(`  club-player statements: ${clubStatements.length}`);
    console.log(`  free-agent statements: ${freeAgentStatements.length}`);
    console.log(`  ambiguous free-agent names skipped: ${ambiguousNames.length}`);
}

main();
